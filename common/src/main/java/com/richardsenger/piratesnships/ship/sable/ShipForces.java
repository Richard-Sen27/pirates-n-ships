package com.richardsenger.piratesnships.ship.sable;

import com.richardsenger.piratesnships.Constants;
import com.richardsenger.piratesnships.platform.Services;
import com.richardsenger.piratesnships.platform.registry.RegistryEntry;
import dev.ryanhcode.sable.api.physics.force.ForceGroup;
import dev.ryanhcode.sable.api.physics.force.ForceGroups;
import net.minecraft.network.chat.Component;
import org.jetbrains.annotations.Nullable;

/**
 * Our Sable force groups ({@code api/physics/force/ForceGroup.java} l.15, registry {@code ForceGroups.REGISTRY_KEY},
 * {@code api/physics/force/ForceGroups.java}). A group is the bucket Sable sums point forces into and shows in its force
 * display; {@code ServerSubLevel#getOrCreateQueuedForceGroup} (l.395) creates the per-body accumulator on first use.
 */
public final class ShipForces {

    /** Translation key of the buoyancy group's name (generated by the hull module's lang provider). */
    public static final String BUOYANCY_KEY = "force_group." + Constants.MOD_ID + ".hull_buoyancy";

    /** Translation key of the sailing group's name (sails and keel, generated by the sailing module's lang provider). */
    public static final String SAILING_KEY = "force_group." + Constants.MOD_ID + ".sailing";

    private static @Nullable RegistryEntry<ForceGroup, ForceGroup> buoyancy;
    private static @Nullable RegistryEntry<ForceGroup, ForceGroup> sailing;

    private ShipForces() {
    }

    /** Registers our groups into Sable's registry. Call from a module's {@code registerContent()}. */
    public static void register() {
        if (buoyancy == null) {
            buoyancy = Services.REGISTRY.register(ForceGroups.REGISTRY_KEY, "hull_buoyancy",
                    () -> new ForceGroup(Component.translatable(BUOYANCY_KEY), null, 0x3a7bd5, true));
        }
        if (sailing == null) {
            sailing = Services.REGISTRY.register(ForceGroups.REGISTRY_KEY, "sailing",
                    () -> new ForceGroup(Component.translatable(SAILING_KEY), null, 0xe0d8b0, true));
        }
    }

    /** The sail and keel force group, or null before {@link #register()} ran. */
    static @Nullable ForceGroup sailing() {
        return sailing != null ? sailing.get() : null;
    }

    /** The dry-volume and flood-water force group, or null before {@link #register()} ran. */
    static @Nullable ForceGroup buoyancy() {
        return buoyancy != null ? buoyancy.get() : null;
    }
}
